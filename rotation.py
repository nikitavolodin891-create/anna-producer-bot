"""Очерёдность форматов и тем рилсов — как у продюсера: каждый день разное, без повторов «опять с подругой».

Код сам выбирает формат и тему дня (по очереди, с учётом того, что уже было), модель пишет сценарий под этот выбор.
"""
from __future__ import annotations

import datetime

# Форматы — из её реальных хитов (anna_profile.PROFILE): 1 и 2 — самые сильные, поэтому встречаются чаще.
FORMATS = {
    "1": "Сценка-диалог с юмором и панчлайном. Второй человек — НЕ обязательно подруга: муж/мужчина, дочь, мама, "
         "коллега, клиентка, или Анна играет обе роли сама (смена кофты/угла камеры).",
    "2": "Сцена + текст на экране под музыку, без речи, 8–20 с. В кадре действие с первой секунды и мини-история "
         "было → поворот → стало (как «две зажигалки»).",
    "3": "Практика/ритуал с понятным шагом, который можно повторить сразу (её «аскеза Соломона», «пошаманим»). "
         "Анна говорит в камеру коротко, до 30 с, первая фраза — что получит зрительница.",
    "5": "Анна одна, юмор: «типы женщин в …», POV, реакция на фразу/комментарий, «что говорит женщина vs что думает». "
         "Без второго человека, быстрые смены кадра.",
    "4": "Пожелание/обращение к зрительнице, 8–12 с, сильная эмоциональная картинка + одна фраза на экране "
         "(как «Желаю тебе однажды сказать…»).",
}
# Неделя: пн..вс. Сильные форматы (1, 2) — 4 раза в неделю.
WEEK = ["1", "2", "3", "5", "2", "1", "4"]

TOPICS = [
    "мужчины и отношения (что он говорит / что она чувствует)",
    "деньги и женщина: просить, получать, платить, свои деньги в паре",
    "подруги и женская поддержка / женская конкуренция",
    "самооценка, тело, возраст, «я недостаточно…»",
    "женская энергия и сила — с юмором над эзотерическими клише",
    "вера, Бог и психология — её самая сильная тема",
    "быт, дети, «всё на мне» — усталость сильной женщины, с юмором",
]


def pick(state: dict, today: datetime.date, n_reels: int = 1) -> tuple[list[tuple[str, str]], dict]:
    """Возвращает [(формат, тема), …] на сегодня и обновлённое состояние очереди.
    Повторный запуск в тот же день даёт тот же выбор."""
    rot = dict(state.get("rot") or {})
    if rot.get("date") == today.isoformat() and rot.get("picks") and all(p[1] in TOPICS for p in rot["picks"]):
        return [tuple(p) for p in rot["picks"]][:max(n_reels, 1)], rot
    ti = int(rot.get("ti", today.toordinal()) or 0)
    recent = list(rot.get("recent_topics") or [])[-4:]
    picks = []
    for k in range(max(n_reels, 1)):
        j = (today.weekday() + k * 3) % 7
        fmt = WEEK[j]
        while picks and fmt in [f for f, _ in picks]:
            j = (j + 1) % 7
            fmt = WEEK[j]
        for _ in range(len(TOPICS)):
            topic = TOPICS[ti % len(TOPICS)]
            ti += 1
            if topic not in recent:
                break
        recent.append(topic)
        picks.append((fmt, topic))
    rot.update(date=today.isoformat(), picks=[list(p) for p in picks], ti=ti, recent_topics=recent[-6:])
    return picks, rot


def plan_text(picks: list[tuple[str, str]]) -> str:
    lines = ["[ФОРМАТ И ТЕМА НА СЕГОДНЯ — выбраны кодом по очереди, чтобы контент не повторялся. Следуй им]"]
    for i, (fmt, topic) in enumerate(picks, 1):
        lines.append(f"Рилс {i}: формат {fmt} — {FORMATS[fmt]}\n  Тема: {topic}. Конкретный угол и ситуацию внутри темы "
                     f"выбери сам по её данным и залетевшим роликам ниши.")
    return "\n".join(lines)
