def _phase(days: int):
    for lo, hi, name, reels, stories, todo in PHASES:
        if lo <= days <= hi:
            return name, reels, stories, todo
    return None


def today_block(today: datetime.date) -> str:
    """Решение на сегодня, посчитанное кодом, + факты о продукте, к которому греем."""
    upcoming = []
    notes = []
    for L in LAUNCHES:
        if L.get("start"):
            d = (L["start"] - today).days
            if d >= 0:
                upcoming.append((d, L))
        elif L.get("month"):
            m = L["month"]
            months_ahead = (m - today.month) % 12
            if months_ahead <= 1:
                notes.append(f"Дата старта {L['name']} ({['', 'январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'][m]}) "
                             f"неизвестна — последней строкой ответа вежливо спроси Анну: «Когда старт {L['name']}? Напиши мне "
                             f"„Запомни: старт … — дата“, и я начну прогрев заранее».")
    upcoming.sort(key=lambda x: x[0])
    lines = [f"[План прогрева на сегодня — решение посчитано кодом по календарю запусков, {today.strftime('%d.%m.%Y')}]"]
    main = next(((d, L) for d, L in upcoming if _phase(d)), None)
    if main:
        d, L = main
        name, reels, stories, todo = _phase(d)
        when = "сегодня" if d == 0 else f"через {d} дн. ({L['start'].strftime('%d.%m')})"
        lines.append(f"ГЛАВНЫЙ ЗАПУСК: {L['name']} — {L['kind']}, старт {when}. Фаза: {name}.")
        lines.append(f"СЕГОДНЯ: рилсов {reels}, сторис-прогрев {stories} шт. Задача сторис: {todo}")
        lines.append(f"Кодовое слово для этого запуска: «{L['cta']}».")
        lines.append("ФАКТЫ О ПРОДУКТЕ (использовать только их; чего нет — не выдумывать):\n" + L["facts"])
    else:
        lines.append("Ближайших запусков в окне прогрева нет. Фаза: ОХВАТ. СЕГОДНЯ: рилсов 2, сторис 2 "
                     "(жизнь Анны, ценности, одно мягкое касание постоянного продукта).")
        lines.append(ALWAYS_ON)
    for d, L in upcoming:
        if main and L is main[1]:
            continue
        if d <= 90:
            lines.append(f"Фоном: {L['name']} — через {d} дн. ({L['start'].strftime('%d.%m')}). "
                         f"Раз в 2–3 дня — одна сторис-касание (без продажи), если сегодня не день главного дедлайна.\n"
                         f"Факты: {L['facts']}")
    lines += notes
    return "\n".join(lines)


def today_plan_line(today: datetime.date) -> str:
    """Одна строка решения: фаза, сколько рилсов и сторис — её вставляем прямо в инструкцию."""
    best = None
    for L in LAUNCHES:
        if L.get("start"):
            d = (L["start"] - today).days
            if d >= 0 and _phase(d) and (best is None or d < best[0]):
                best = (d, L)
    if not best:
        return "фаза ОХВАТ (запусков в окне прогрева нет): рилсов 2, сторис 2."
    d, L = best
    name, reels, stories, _ = _phase(d)
    when = "сегодня старт" if d == 0 else f"до старта {d} дн."
    return f"{L['name']}: {when}, фаза {name} — рилсов {reels}, сторис {stories}, кодовое слово «{L['cta']}»."


def today_reels(today: datetime.date) -> int:
    """Сколько рилсов на сегодня по фазе запуска (вне запусков — 2)."""
    best = None
    for L in LAUNCHES:
        if L.get("start"):
            d = (L["start"] - today).days
            if d >= 0 and _phase(d) and (best is None or d < best):
                best = d
    return _phase(best)[1] if best is not None else 2
